import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {curriculum,phases,videos,totalHours} from './course.js';
const store=new Map();
const root={innerHTML:''};
const els={'#app':root,'#profile-switch':{addEventListener(){}},'#toast':{textContent:'',style:{},classList:{add(){},remove(){}}}};
const handlers={};
const doc={querySelector(q){return els[q]??null},querySelectorAll(){return []},addEventListener(type,handler){handlers[type]=handler},visibilityState:'visible'};
const loc={hash:'#/dashboard',pathname:'/V2/',search:'',replace(v){this.hash='#'+v.split('#')[1]}};
const cloud={authenticated:false,available:false,config:{},session:null};
const ctx=vm.createContext({__course:{curriculum,phases,videos,totalHours},__cloud:{cloud},localStorage:{getItem(k){return store.get(k)||null},setItem(k,v){store.set(k,v)},removeItem(k){store.delete(k)}},document:doc,window:{addEventListener(){},scrollTo(){}},location:loc,console,Date,Intl,Math,Number,Object,JSON,URL,Array,Set,Map,setTimeout(){return 1},clearTimeout(){},setInterval(){return 1},confirm(){return true}});
let source=fs.readFileSync(new URL('./app.js',import.meta.url),'utf8');
source=source.replace(/^import \{curriculum,phases,videos,totalHours\} from '\.\/course\.js';\nimport \{cloud\} from '\.\/cloud\.js';/,'const {curriculum,phases,videos,totalHours}=globalThis.__course; const {cloud}=globalThis.__cloud;');
vm.runInContext(source,ctx,{timeout:10000});
assert.match(root.innerHTML,/Our learning journey/);
assert.match(root.innerHTML,/Learn side by side/);
assert.match(root.innerHTML,/720 study blocks/);
assert.doesNotMatch(root.innerHTML,/leaderboard|points|10 pts\/block|\bvs\b/i);
assert.match(root.innerHTML,/0\.0%/);
vm.runInContext('mutate(1,r=>r.blocks=[0])',ctx);
assert.equal(vm.runInContext("stats('local-you').doneBlocks",ctx),1);
assert.equal(vm.runInContext("stats('local-you').blockPercent",ctx),'0.1');
assert.equal(vm.runInContext('sharedStats().blocks',ctx),0);
vm.runInContext("state.activeId='local-friend';mutate(1,r=>r.blocks=[0,1])",ctx);
assert.equal(vm.runInContext('sharedStats().blocks',ctx),1);
assert.equal(vm.runInContext('sharedStats().days',ctx),0);
assert.equal(vm.runInContext("stats('local-friend').doneBlocks",ctx),2);
assert.equal(vm.runInContext("stats('local-you').doneBlocks",ctx),1);
loc.hash='#/together';vm.runInContext('render()',ctx);
assert.match(root.innerHTML,/<h1>Study Together<\/h1>/);
assert.match(root.innerHTML,/Our 120-day study checklist/);
assert.match(root.innerHTML,/Set Day 1 as our shared lesson/);
assert.match(root.innerHTML,/1 of 720 blocks completed together/);
assert.equal((root.innerHTML.match(/class="day-jump"/g)||[]).length,120);
assert.match(root.innerHTML,/1\/6 blocks/);
assert.match(root.innerHTML,/2\/6 blocks/);
await handlers.click({target:{closest(){return {dataset:{action:'set-shared-day',day:'8'}}}}});
assert.match(root.innerHTML,/Day 8:/);
const saved=JSON.parse(store.get('v2_v3'));
assert.equal(saved.sharedDay,8);
assert.deepEqual(saved.users.filter(u=>u.id.startsWith('local-')).map(u=>u.name),['Praveen','Sanchita']);
// Closing/reopening browser should recover independent local data and shared day.
vm.runInContext('state=load()',ctx);
assert.equal(vm.runInContext('getSharedDay()',ctx),8);
assert.equal(vm.runInContext("stats('local-you').doneBlocks",ctx),1);
assert.equal(vm.runInContext("stats('local-friend').doneBlocks",ctx),2);
// Cloud: both sides are shown, but edits remain tied to own cloud account.
cloud.authenticated=true;
cloud.session={user:{id:'11111111-1111-4111-8111-111111111111',email:'praveen@example.test'}};
let rpcDay=0;cloud.setStudyDay=async day=>{rpcDay=day;return day};
vm.runInContext("state.users.push({id:'cloud:11111111-1111-4111-8111-111111111111',name:'Praveen'})",ctx);
vm.runInContext("state.activeId='cloud:11111111-1111-4111-8111-111111111111'",ctx);
vm.runInContext("state.progress['cloud:11111111-1111-4111-8111-111111111111']={1:{blocks:[0,1,2],seconds:{},notes:'',updatedAt:123}}",ctx);
vm.runInContext("state.progress['cloud:22222222-2222-4222-8222-222222222222']={1:{blocks:[0,1,2,3],seconds:{},notes:'',updatedAt:234}}",ctx);
vm.runInContext("peer={members:[{id:'11111111-1111-4111-8111-111111111111',display_name:'Praveen'},{id:'22222222-2222-4222-8222-222222222222',display_name:'Sanchita'}],team:{invite_code:'DEMO',study_day:9}}",ctx);
loc.hash='#/together';vm.runInContext('render()',ctx);
assert.equal(vm.runInContext('getSharedDay()',ctx),9);
assert.equal(vm.runInContext('sharedStats().blocks',ctx),3);
await handlers.click({target:{closest(){return {dataset:{action:'set-shared-day',day:'12'}}}}});
assert.equal(rpcDay,12);
assert.equal(vm.runInContext('getSharedDay()',ctx),12);
assert.match(root.innerHTML,/Day 12:/);
assert.match(root.innerHTML,/Your account/);
assert.match(root.innerHTML,/3\/6 blocks/);
assert.match(root.innerHTML,/4\/6 blocks/);
assert.doesNotMatch(root.innerHTML,/Waiting for the second learner/);
assert.doesNotMatch(root.innerHTML,/leaderboard|10 pts\/block|\bvs\b/i);
loc.hash='#/dashboard';vm.runInContext('render()',ctx);
assert.match(root.innerHTML,/value="cloud:11111111-1111-4111-8111-111111111111"/);
assert.doesNotMatch(root.innerHTML,/option value="local-friend"/);
assert.match(root.innerHTML,/Learn side by side/);
console.log('PASS: Study Together labels; two independent bars; shared-day state; jointly finished blocks; 120-day study checklist; local persistence; cloud-backed partner reads.');
